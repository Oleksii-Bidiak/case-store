// design-sync: compile the admin's Tailwind v4 utilities into a single static
// stylesheet for the DS bundle's cfg.cssEntry.
//
// store-admin has no precompiled stylesheet — utilities like `bg-primary` only
// exist after Tailwind v4 scans the sources. We reuse the app's real token
// definitions from src/app/globals.css (so the DS stays in lockstep with the
// admin), scan the WHOLE admin src (so every layout utility the admin uses
// exists for the design agent's glue) plus the authored previews, and emit a
// self-contained file. Run from the repo root:
//   node .design-sync-admin/build/compile-css.mjs
// (run.mjs calls it before every build/resync.)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

const here = dirname(fileURLToPath(import.meta.url)); // .design-sync-admin/build
const repoRoot = resolve(here, "..", "..");
const globalsCss = resolve(repoRoot, "apps/store-admin/src/app/globals.css");
const genDir = resolve(here, ".generated");
const inputPath = resolve(genDir, "tailwind-input.css");
const outPath = resolve(repoRoot, "apps/store-admin/.ds-sync-css/ui.css");

function mustReplace(src, re, by, what) {
  if (!re.test(src)) {
    throw new Error(
      `[compile-css] ${what} not found in apps/store-admin/src/app/globals.css — its format changed; update the regex in .design-sync-admin/build/compile-css.mjs`,
    );
  }
  return src.replace(re, by);
}

// Strip the app's own `@import 'tailwindcss'` / typography plugin lines; we
// re-add them with explicit, scoped source detection.
let globals = readFileSync(globalsCss, "utf8");
globals = mustReplace(
  globals,
  /^\s*@import\s+['"]tailwindcss['"];?\s*$/m,
  "",
  "@import 'tailwindcss'",
);
globals = mustReplace(
  globals,
  /^\s*@plugin\s+['"]@tailwindcss\/typography['"];?\s*$/m,
  "",
  "@plugin '@tailwindcss/typography'",
);

// Theme opt-out. The admin switches every token to dark under a BARE
// `@media (prefers-color-scheme: dark) { :root { … } }` — no data-theme guard
// (the storefront has one). Preview cards and design canvases paint a fixed
// white background, so on a dark-OS viewer that is light text on white. Give
// the block the storefront's shape: the media query applies only to
// `:root:not([data-theme="light"])` (the bundle prelude sets
// data-theme="light"), and `:root[data-theme="dark"]` opts in explicitly.
// Without the attribute the cascade is exactly the app's.
const darkRe =
  /@media\s*\(prefers-color-scheme:\s*dark\)\s*\{\s*:root\s*\{([\s\S]*?)\n\s*\}\s*\n\}/;
const darkMatch = globals.match(darkRe);
if (!darkMatch) {
  throw new Error(
    "[compile-css] dark-mode block `@media (prefers-color-scheme: dark) { :root { … } }` not found in globals.css — update darkRe in .design-sync-admin/build/compile-css.mjs",
  );
}
const darkBody = darkMatch[1];
globals = globals.replace(
  darkRe,
  `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {${darkBody}\n  }\n}\n:root[data-theme="dark"] {${darkBody}\n}`,
);

// The brand fonts (Geist / Geist Mono / Sora) are injected by next/font at
// runtime in the admin (src/app/layout.tsx), so --font-geist-sans /
// --font-geist-mono / --font-sora are undefined in a standalone bundle. Load
// them from Google Fonts and define the vars.
const fontImport =
  "@import url('https://fonts.googleapis.com/css2?family=Geist:wght@300..700&family=Geist+Mono:wght@400..600&family=Sora:wght@400..700&display=swap');";
const fontVars = `:root {
  --font-geist-sans: 'Geist', ui-sans-serif, system-ui, -apple-system, sans-serif;
  --font-geist-mono: 'Geist Mono', ui-monospace, SFMono-Regular, monospace;
  --font-sora: 'Sora', var(--font-geist-sans);
}`;

const input = `/* generated by .design-sync-admin/build/compile-css.mjs — do not edit */
${fontImport}
@import 'tailwindcss' source(none);
@source "../../../apps/store-admin/src/**/*.{ts,tsx}";
@source "../../previews/**/*.tsx";
@plugin '@tailwindcss/typography';
/* Safelist the semantic-token utilities so the design agent can use the full
   token vocabulary (the conventions header names these), not just the subset
   the scanned components happen to use. */
@source inline("{bg,text,border}-{background,foreground,primary,primary-foreground,secondary,secondary-foreground,muted,muted-foreground,accent,accent-foreground,card,card-foreground,popover,popover-foreground,sale,sale-foreground,success,success-foreground,warning,warning-foreground,destructive,destructive-foreground,border,input,ring,overlay}");
@source inline("shadow-{card,elevated,lift}");
@source inline("rounded-{sm,md,lg,xl,2xl}");
@source inline("font-{sans,mono,display}");
${globals}
${fontVars}`;

mkdirSync(genDir, { recursive: true });
writeFileSync(inputPath, input);
mkdirSync(dirname(outPath), { recursive: true });

const result = await postcss([tailwindcss()]).process(input, {
  from: inputPath,
  to: outPath,
});
writeFileSync(outPath, result.css);
console.error(
  `css: wrote ${outPath} (${(result.css.length / 1024).toFixed(0)} KB)`,
);
