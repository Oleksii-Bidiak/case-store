// design-sync: compile the storefront's Tailwind v4 utilities into a single
// static stylesheet for the DS bundle's cfg.cssEntry.
//
// store-client has no precompiled stylesheet — utilities like `bg-primary`
// only exist after Tailwind v4 scans the component sources. We reuse the
// app's real token definitions from src/app/globals.css (so the DS stays in
// lockstep with the brand), but scope content scanning to shared/** and emit
// a self-contained file. Run from the repo root:  node .design-sync/build/compile-css.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

const here = dirname(fileURLToPath(import.meta.url)); // .design-sync/build
const repoRoot = resolve(here, "..", "..");
const globalsCss = resolve(
  repoRoot,
  "apps/store-client/src/app/globals.css",
);
const genDir = resolve(here, ".generated");
const inputPath = resolve(genDir, "tailwind-input.css");
const outPath = resolve(
  repoRoot,
  "apps/store-client/.ds-sync-css/ui.css",
);

// Strip the app's own `@import 'tailwindcss'` / typography plugin lines; we
// re-add them with explicit, scoped source detection. Everything else
// (:root tokens, @theme inline, base styles) is kept verbatim.
const globals = readFileSync(globalsCss, "utf8")
  .replace(/^\s*@import\s+['"]tailwindcss['"];?\s*$/m, "")
  .replace(/^\s*@plugin\s+['"]@tailwindcss\/typography['"];?\s*$/m, "");

// The brand fonts (Geist / Geist Mono / Sora) are injected by next/font at
// runtime in the app, so --font-geist-sans / --font-geist-mono / --font-sora
// are undefined in a standalone bundle. Load them from Google Fonts and define
// the vars so the DS renders in the real brand families (display = Sora).
const fontImport =
  "@import url('https://fonts.googleapis.com/css2?family=Geist:wght@300..700&family=Geist+Mono:wght@400..600&family=Sora:wght@400..700&display=swap');";
const fontVars = `:root {
  --font-geist-sans: 'Geist', ui-sans-serif, system-ui, -apple-system, sans-serif;
  --font-geist-mono: 'Geist Mono', ui-monospace, SFMono-Regular, monospace;
  --font-sora: 'Sora', var(--font-geist-sans);
}`;

const input = `/* generated by .design-sync/build/compile-css.mjs — do not edit */
${fontImport}
@import 'tailwindcss' source(none);
@source "../../../apps/store-client/src/**/*.{ts,tsx}";
@source "../../previews/**/*.tsx";
@plugin '@tailwindcss/typography';
/* Safelist the semantic-token utilities so the design agent can use the full
   token vocabulary (the conventions header names these), not just the subset
   the scanned components happen to use. */
@source inline("{bg,text,border}-{background,foreground,primary,primary-foreground,secondary,secondary-foreground,muted,muted-foreground,accent,accent-foreground,card,card-foreground,popover,popover-foreground,sale,sale-foreground,success,success-foreground,warning,warning-foreground,destructive,destructive-foreground,border,input,ring}");
@source inline("shadow-{card,elevated,lift}");
@source inline("rounded-{sm,md,lg,xl,2xl}");
@source inline("font-{sans,mono,display}");
${globals}
${fontVars}`;

mkdirSync(genDir, { recursive: true });
writeFileSync(inputPath, input);
mkdirSync(dirname(outPath), { recursive: true });

const result = await postcss([tailwindcss()]).process(input, {
  from: inputPath,
  to: outPath,
});
writeFileSync(outPath, result.css);
console.error(
  `css: wrote ${outPath} (${(result.css.length / 1024).toFixed(0)} KB)`,
);
